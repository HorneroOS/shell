#!/usr/bin/env python3
"""Build Hornero Glyphs: a curated Tabler Icons (outline, MIT) subset.

Reads glyph names from assets/fonts/hornero-glyphs.names, fetches the
pinned @tabler/icons-webfont release, verifies its SHA-256, subsets the
outline font with fontTools (pyftsubset) and writes:

  assets/fonts/hornero-glyphs.ttf   (family "Hornero Glyphs")
  assets/fonts/LICENSE.tabler-icons (upstream MIT licence, verbatim)
  utils/GlyphMap.js                 (name -> codepoint table)

Usage:
  python3 scripts/build-glyphs.py            # rebuild
  python3 scripts/build-glyphs.py --check    # fail if GlyphMap.js drifts
  python3 scripts/build-glyphs.py --tarball PATH   # offline, local tgz

The downloaded archive is treated as untrusted data: only the three
needed members are read, by exact name, straight from the archive.
"""

from __future__ import annotations

import argparse
import hashlib
import io
import re
import sys
import tarfile
import tempfile
import urllib.request
from pathlib import Path

TABLER_VERSION = "3.50.0"
TABLER_URL = (
    "https://registry.npmjs.org/@tabler/icons-webfont/-/"
    f"icons-webfont-{TABLER_VERSION}.tgz"
)
TABLER_SHA256 = "1afa9b3764607de419b4eeff296f2328361a5ba605ebd35812832f61ddbf070e"
FAMILY = "Hornero Glyphs"

ROOT = Path(__file__).resolve().parent.parent
NAMES = ROOT / "assets" / "fonts" / "hornero-glyphs.names"
FONT_OUT = ROOT / "assets" / "fonts" / "hornero-glyphs.ttf"
LICENSE_OUT = ROOT / "assets" / "fonts" / "LICENSE.tabler-icons"
MAP_OUT = ROOT / "utils" / "GlyphMap.js"

MEMBER_TTF = "package/dist/fonts/tabler-icons.ttf"
MEMBER_CSS = "package/dist/tabler-icons.css"
MEMBER_LICENSE = "package/LICENSE"

CSS_RULE = re.compile(r'\.ti-([a-z0-9-]+):before\s*\{\s*content:\s*"\\([0-9a-f]+)"')


def read_names() -> list[str]:
    names = []
    for line in NAMES.read_text(encoding="utf-8").splitlines():
        line = line.strip()
        if line and not line.startswith("#"):
            names.append(line)
    if len(names) != len(set(names)):
        raise SystemExit("build-glyphs: duplicate names in hornero-glyphs.names")
    return sorted(names)


def fetch(tarball: str | None) -> bytes:
    if tarball:
        data = Path(tarball).read_bytes()
    else:
        with urllib.request.urlopen(TABLER_URL, timeout=60) as resp:  # noqa: S310 (pinned https URL)
            data = resp.read()
    digest = hashlib.sha256(data).hexdigest()
    if digest != TABLER_SHA256:
        raise SystemExit(
            f"build-glyphs: sha256 mismatch for @tabler/icons-webfont {TABLER_VERSION}: {digest}"
        )
    return data


def members(data: bytes) -> dict[str, bytes]:
    out = {}
    with tarfile.open(fileobj=io.BytesIO(data), mode="r:gz") as tar:
        for name in (MEMBER_TTF, MEMBER_CSS, MEMBER_LICENSE):
            info = tar.getmember(name)
            if not info.isfile():
                raise SystemExit(f"build-glyphs: {name} is not a regular file")
            handle = tar.extractfile(info)
            assert handle is not None
            out[name] = handle.read()
    return out


def codepoints(css: str, names: list[str]) -> dict[str, int]:
    table = {name: int(cp, 16) for name, cp in CSS_RULE.findall(css)}
    missing = [n for n in names if n not in table]
    if missing:
        raise SystemExit(f"build-glyphs: not in Tabler {TABLER_VERSION}: {', '.join(missing)}")
    return {n: table[n] for n in names}


def render_map(table: dict[str, int]) -> str:
    rows = ",\n".join(f'    "{name}": 0x{cp:X}' for name, cp in table.items())
    return (
        "// GENERATED by scripts/build-glyphs.py from Tabler Icons "
        f"{TABLER_VERSION} (MIT). Do not edit.\n"
        ".pragma library\n\n"
        f'var family = "{FAMILY}";\n\n'
        "var codepoints = {\n"
        f"{rows}\n"
        "};\n"
    )


def subset(ttf: bytes, table: dict[str, int]) -> bytes:
    from fontTools import subset as ftsubset
    from fontTools.ttLib import TTFont

    with tempfile.TemporaryDirectory() as tmp:
        src = Path(tmp) / "tabler-icons.ttf"
        dst = Path(tmp) / "hornero-glyphs.ttf"
        src.write_bytes(ttf)
        unicodes = ",".join(f"U+{cp:04X}" for cp in sorted(table.values()))
        ftsubset.main([
            str(src),
            f"--unicodes={unicodes}",
            f"--output-file={dst}",
            "--layout-features=",
            "--no-hinting",
            "--desubroutinize",
            "--name-IDs=*",
        ])
        font = TTFont(str(dst))
        for record in font["name"].names:
            if record.nameID in (1, 4, 16):
                record.string = FAMILY
            elif record.nameID == 6:
                record.string = FAMILY.replace(" ", "")
            elif record.nameID == 3:
                record.string = f"{FAMILY} (Tabler Icons {TABLER_VERSION})"
        if "head" in font:
            # Deterministic output: pin timestamps.
            font["head"].created = 0
            font["head"].modified = 0
        out = io.BytesIO()
        font.save(out)
        return out.getvalue()


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true", help="verify utils/GlyphMap.js is current")
    parser.add_argument("--tarball", help="local @tabler/icons-webfont tgz (offline build)")
    args = parser.parse_args()

    names = read_names()
    files = members(fetch(args.tarball))
    table = codepoints(files[MEMBER_CSS].decode("utf-8"), names)
    rendered = render_map(table)

    if args.check:
        if MAP_OUT.read_text(encoding="utf-8") != rendered:
            print("build-glyphs: utils/GlyphMap.js is stale; re-run scripts/build-glyphs.py", file=sys.stderr)
            return 1
        print(f"build-glyphs: OK ({len(table)} glyphs)")
        return 0

    FONT_OUT.write_bytes(subset(files[MEMBER_TTF], table))
    LICENSE_OUT.write_bytes(files[MEMBER_LICENSE])
    MAP_OUT.write_text(rendered, encoding="utf-8")
    print(f"build-glyphs: wrote {len(table)} glyphs to {FONT_OUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
